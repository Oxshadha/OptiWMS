import { apiClient } from './client';

export interface Location {
  id: string;
  warehouseId: string;
  locationCode: string;
  area?: string;
  rowNumber?: string;
  bayNumber?: string;
  levelNumber?: number;
  binPosition?: string;
  locationType?: string;
  zoneType?: string; // STORAGE, STAGING, RECEIVING, SHIPMENT, PACKING
  capacity?: number;
  isActive: boolean;
  qrCode?: string;
  createdAt?: string;
  // Rack system fields
  rackStatus?: string;
  amalgamatedClass?: string;
  description?: string;
  notes?: string;
  accessibilityRating?: number;
  coordinateX?: number;
  coordinateY?: number;
  maxPalletCapacity?: number;
  currentPalletCount?: number;
  maxWeightKg?: number;
  maxVolumeCm3?: number;
  maxLpnCount?: number;
}

