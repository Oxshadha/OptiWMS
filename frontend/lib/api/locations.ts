export interface LocationHierarchy {
  warehouseId: string;
  hierarchy: {
    [area: string]: {
      [row: string]: {
        [bay: string]: Location[];
      };
    };
  };
}

export const locationsApi = {
  getAll: async (): Promise<Location[]> => {
    return apiClient.get<Location[]>('/master/locations');
  },

  getById: async (id: string): Promise<Location> => {
    return apiClient.get<Location>(`/master/locations/${id}`);
  },

  getByCode: async (locationCode: string): Promise<Location> => {
    return apiClient.get<Location>(`/master/locations/code/${locationCode}`);
  },

  getByWarehouse: async (warehouseId: string): Promise<Location[]> => {
    return apiClient.get<Location[]>(`/master/locations/warehouse/${warehouseId}`);
  },

  /**
   * Get only storage locations (exclude staging, receiving, shipment, packing areas)
   * For warehouse map visualization - only show racks, not staging areas
   */
  getStorageLocationsByWarehouse: async (warehouseId: string): Promise<Location[]> => {
    return apiClient.get<Location[]>(`/master/locations/warehouse/${warehouseId}/storage-only`);
  },

  getRackOccupancy: async (warehouseId: string): Promise<BinOccupancy[]> => {
    return apiClient.get<BinOccupancy[]>(`/master/locations/warehouse/${warehouseId}/rack-occupancy`);
  },

  getRackSummaries: async (
    warehouseId: string,
    options?: { limit?: number; offset?: number }
  ): Promise<RackSummary[]> => {
    const params = new URLSearchParams();
    if (options?.limit != null) params.set("limit", String(options.limit));
    if (options?.offset != null) params.set("offset", String(options.offset));
    const query = params.toString();
    return apiClient.get<RackSummary[]>(
      `/master/locations/warehouse/${warehouseId}/rack-summaries${query ? `?${query}` : ""}`
    );
  },

  getOperationalStations: async (warehouseId: string): Promise<OperationalStation[]> => {
    return apiClient.get<OperationalStation[]>(
      `/master/locations/warehouse/${warehouseId}/operational-stations`
    );
  },

  getRackDetail: async (warehouseId: string, rackId: string): Promise<BinOccupancy[]> => {
    const params = new URLSearchParams({ rackId });
    return apiClient.get<BinOccupancy[]>(`/master/locations/warehouse/${warehouseId}/rack-detail?${params.toString()}`);
  },

  getIntegritySummary: async (warehouseId: string): Promise<IntegritySummary> => {
    return apiClient.get<IntegritySummary>(`/master/locations/warehouse/${warehouseId}/integrity-summary`);
  },

  createPlacementPlan: async (body: {
    warehouseId: string;
    materialId: string;
    totalQuantity: number;
    preferredLocationCode?: string;
    excludeLocationCodes?: string[];
  }): Promise<PlacementPlan> => {
    return apiClient.post<PlacementPlan>("/master/locations/placement-plan", body);
  },

  getHierarchyByWarehouse: async (warehouseId: string): Promise<LocationHierarchy> => {
    // Backend returns { warehouseId, hierarchy } but we need to transform it
    const response = await apiClient.get<{ warehouseId: string; hierarchy: any }>(`/master/locations/hierarchy?warehouseId=${warehouseId}`);
    return {
      warehouseId: response.warehouseId,
      hierarchy: response.hierarchy,
    };
  },
  
  getHierarchy: async (warehouseId: string): Promise<LocationHierarchy> => {
    // Alias for getHierarchyByWarehouse
    return locationsApi.getHierarchyByWarehouse(warehouseId);
  },

  create: async (location: CreateLocationRequest): Promise<Location> => {
    return apiClient.post<Location>('/master/locations', location);
  },

  update: async (id: string, location: UpdateLocationRequest): Promise<Location> => {
    return apiClient.put<Location>(`/master/locations/${id}`, location);
  },

  delete: async (id: string): Promise<void> => {
    return apiClient.delete<void>(`/master/locations/${id}`);
  },

  // Rack-specific endpoints
  updateRack: async (id: string, updates: UpdateRackRequest): Promise<Location> => {
    return apiClient.put<Location>(`/master/locations/racks/${id}`, updates);
  },

  bulkCreateRacks: async (request: BulkCreateRacksRequest): Promise<BulkCreateRacksResponse> => {
    return apiClient.post<BulkCreateRacksResponse>('/master/locations/bulk-racks', request);
  },

  deleteRack: async (
    warehouseId: string,
    area: string,
    rowNumber: string,
    bayNumber: string
  ): Promise<RackDeleteResponse> => {
    const params = new URLSearchParams({
      warehouseId,
      area,
      rowNumber,
      bayNumber,
    });
    return apiClient.delete<RackDeleteResponse>(`/master/locations/racks?${params.toString()}`);
  },
};
